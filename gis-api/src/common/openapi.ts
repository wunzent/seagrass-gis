import type { INestApplication } from '@nestjs/common';
import { DocumentBuilder, OpenAPIObject, SwaggerModule } from '@nestjs/swagger';
import { dump } from 'js-yaml';
import { SCHEMAS } from './openapi-schemas';

/** Single source: the document is generated from controller decorators plus the shared component schemas. */
export function buildOpenApiDocument(app: INestApplication): OpenAPIObject {
  const config = new DocumentBuilder()
    .setTitle('Seagrass GIS API')
    .setDescription('API ติดตามแหล่งหญ้าทะเล; write endpoints ใช้ HttpOnly cookie gis_access + Origin + X-CSRF-Protection: 1')
    .setVersion('0.1.0')
    .addCookieAuth('gis_access', { type: 'apiKey', in: 'cookie', name: 'gis_access' }, 'gis_access')
    .build();
  const document = SwaggerModule.createDocument(app, config);
  document.components = { ...document.components, schemas: { ...(SCHEMAS as unknown as Record<string, object>), ...document.components?.schemas } };
  return document;
}

/** Serves Swagger UI at /docs and the generated spec at /docs/openapi.json and /docs/openapi.yaml. */
export function setupDocs(app: INestApplication) {
  SwaggerModule.setup('docs', app, () => buildOpenApiDocument(app), {
    jsonDocumentUrl: 'docs/openapi.json', yamlDocumentUrl: 'docs/openapi.yaml',
  });
}

const slug = (path: string) => path.replace(/^\//, '').replace(/[^A-Za-z0-9]+/g, '_').replace(/_$/, '') || 'root';
const yaml = (value: unknown) => dump(value, { noRefs: true, lineWidth: 120, sortKeys: false });

function rewriteRefs(value: unknown, prefix: string): unknown {
  if (Array.isArray(value)) return value.map(v => rewriteRefs(v, prefix));
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).map(([k, v]) =>
      [k, k === '$ref' && typeof v === 'string' && v.startsWith('#/components/schemas/')
        ? `${prefix}${v.slice('#/components/schemas/'.length)}.yaml` : rewriteRefs(v, prefix)]));
  }
  return value;
}

/** Modular layout for api-docs/: openapi.yaml → paths/<route>.yaml → components/schemas/<Name>.yaml (relative $refs). */
export function renderApiDocs(document: OpenAPIObject): Map<string, string> {
  const files = new Map<string, string>();
  const paths: Record<string, { $ref: string }> = {};
  for (const [route, item] of Object.entries(document.paths)) {
    const file = `paths/${slug(route)}.yaml`;
    paths[route] = { $ref: `./${file}` };
    files.set(file, yaml(rewriteRefs(item, '../components/schemas/')));
  }
  const schemas: Record<string, { $ref: string }> = {};
  for (const [name, schema] of Object.entries(document.components?.schemas ?? {})) {
    schemas[name] = { $ref: `./components/schemas/${name}.yaml` };
    files.set(`components/schemas/${name}.yaml`, yaml(rewriteRefs(schema, './')));
  }
  const root = { ...document, paths, components: { ...document.components, schemas } };
  files.set('openapi.yaml', `# Generated by \`npm run docs:generate\` from controller decorators; do not edit by hand.\n${yaml(root)}`);
  return files;
}
